#!/usr/bin/env python3
"""Writes firmware/sound-events/sound_events_config.h from calibrate.py's result, so the chip's alert settings are exactly
the ones that were scored on recordings the tuning never saw.

  python3 make_config.py <calibrated.json> <classes.json> <out header>
"""
import json
import sys
from pathlib import Path

result = json.loads(Path(sys.argv[1]).read_text())
classes = [c for c in json.loads(Path(sys.argv[2]).read_text()) if c != "background"]
URGENT = {"glass_breaking", "scream", "gunshot", "alarm", "baby_crying"}
SUSTAINED = {"water_running": 600}   # seconds before "left running" is reported
rows = []
for cls in classes:
    r = result.get(cls)
    if r is None:
        rows.append(f'    {{"{cls}", 1.01f, 1.01f, 1, 30, 0, 0}},  /* no setting met the false-alarm budget: never fires */')
        continue
    thr = r["threshold"]
    corroborated = max(0.5, round(thr - 0.1, 2))
    rows.append(f'    {{"{cls}", {thr:.2f}f, {corroborated:.2f}f, {r["hits"]}, 30, {SUSTAINED.get(cls, 0)}, {1 if cls in URGENT else 0}}},'
                f'  /* unseen check: {r["check_found"]}/{r["check_total"]} found, {r["check_false_per_hour"]} false/h */')
Path(sys.argv[3]).write_text(
    "// Generated by test/dev/sound-eval/tiny/make_config.py from calibrate.py. Do not edit by hand.\n"
    "// Class order = the model's output order after the background score (scores[1 + i]).\n"
    '#include "sound_events.h"\n\n'
    "static const se_class_cfg_t SOUND_EVENT_CONFIG[] = {\n" + "\n".join(rows) + "\n};\n"
    f"#define SOUND_EVENT_CLASSES {len(classes)}\n")
print(f"wrote {sys.argv[3]}")
